const oldUuid='3ca9811d1a42d086';
const sourceUuid='6da689cbfc28e476';
const schematicUuid='416c10313f778784';
const boardName='mcu_board';
const before=await eda.dmt_Board.getBoardInfo(boardName);
if(before?.schematic?.uuid!==schematicUuid||before?.pcb?.uuid!==oldUuid)throw new Error('Initial board association changed');
const source=await eda.dmt_Pcb.getPcbInfo(sourceUuid);
if(source?.name!=='STM32H747_PCB_WORK'||source.parentBoardName)throw new Error('Validated staging PCB identity changed');
const backup=await eda.sys_FileSystem.readFileFromFileSystem('C:/Dev/EasyEDA/EasyEDA-Project/STM32H747 board/output/checkpoints/STM32H747_after_stack_ui_native_20261014.epro2');
if(!backup||backup.size<18000000)throw new Error('Verified full recovery checkpoint unavailable');
const expected=['e8a4e3fabe30ab59','360993a3108b5759','c0b1ffcb620d758f','3c13ef086afba6f5','a07bf8e4331877a8'];
const verifyPages=async()=>{const pages=await eda.dmt_Schematic.getAllSchematicPagesInfo();if(pages.length!==5||expected.some(uuid=>!pages.some(p=>p.uuid===uuid&&p.parentSchematicUuid===schematicUuid)))throw new Error('Five-page schematic guard failed');return pages;};
await verifyPages();
const deleted=await eda.dmt_Pcb.deletePcb(oldUuid);
if(!deleted)throw new Error('Initial scoped PCB removal failed');
await new Promise(r=>setTimeout(r,700));
const interim=await eda.dmt_Board.getBoardInfo(boardName);
if(interim?.schematic?.uuid!==schematicUuid||interim.pcb)throw new Error('Unexpected board state after initial PCB removal');
await verifyPages();
const copiedUuid=await eda.dmt_Pcb.copyPcb(sourceUuid,boardName);
await new Promise(r=>setTimeout(r,1600));
const after=await eda.dmt_Board.getBoardInfo(boardName);
const info=copiedUuid?await eda.dmt_Pcb.getPcbInfo(copiedUuid):null;
const report={deleted,oldUuid,copiedUuid,before,interim,after,info,pages:await verifyPages(),pcbs:await eda.dmt_Pcb.getAllPcbsInfo()};
const path='C:/Dev/EasyEDA/EasyEDA-Project/STM32H747 board/output/validation/native-final-pcb-replacement-receipt.json';
const saved=await eda.sys_FileSystem.saveFileToFileSystem(path,new Blob([JSON.stringify(report,null,2)]),undefined,false);
if(!copiedUuid||after?.pcb?.uuid!==copiedUuid||after.schematic?.uuid!==schematicUuid||info?.parentBoardName!==boardName)throw new Error('Final PCB association failed; inspect saved receipt');
return {saved,path,deleted,oldUuid,copiedUuid,info,pages:report.pages,boardUuid:after.uuid};
