const uuid='6da689cbfc28e476';
const expectedProject='761c4fdb8e3e1a273a7eb212bd6961ba8b6efdb0e27d1b0c207735a7e696c24c';
const project=await eda.dmt_Project.getCurrentProjectInfo();
if(project?.uuid!==expectedProject)throw new Error('Dedicated STM32H747 project mismatch');
const target=(await eda.dmt_Pcb.getAllPcbsInfo()).find(p=>p.uuid===uuid);
if(target?.name!=='STM32H747_PCB_WORK')throw new Error('Dedicated PCB staging identity mismatch');
const tab=await eda.dmt_EditorControl.openDocument(uuid);
if((await eda.dmt_Pcb.getCurrentPcbInfo())?.uuid!==uuid)throw new Error('Wrong staging PCB document');
const before=await eda.pcb_Layer.getAllLayers();
const configured=await eda.pcb_Layer.setTheNumberOfCopperLayers(6);
const after=await eda.pcb_Layer.getAllLayers();
if(!configured)throw new Error('Six-layer configuration rejected');
const saved=await eda.pcb_Document.save();
