await eda.dmt_EditorControl.closeDocument(tab);
await eda.dmt_EditorControl.openDocument(uuid);
if((await eda.dmt_Pcb.getCurrentPcbInfo())?.uuid!==uuid)throw new Error('Wrong reopened staging PCB');
const reopened=await eda.pcb_Layer.getAllLayers();
const liveComponents=(await eda.pcb_PrimitiveComponent.getAll(1)).length;
if(liveComponents!==330)throw new Error('Placement contract changed during layer configuration');
const source=await eda.sys_FileManager.getDocumentSource();
const captured=await eda.sys_FileSystem.saveFileToFileSystem('C:/Dev/EasyEDA/EasyEDA-Project/STM32H747 board/output/validation/native-six-layer-configured.epru',new Blob([source]),undefined,false);
const reportSaved=await eda.sys_FileSystem.saveFileToFileSystem('C:/Dev/EasyEDA/EasyEDA-Project/STM32H747 board/output/validation/native-six-layer-configured.json',new Blob([JSON.stringify({uuid,configured,saved,liveComponents,before,after,reopened},null,2)]),undefined,false);
return {uuid,configured,saved,captured,reportSaved,liveComponents,reopenedLayers:reopened.filter(l=>[1,2,15,16,17,18].includes(l.id))};
