const root='C:/Dev/EasyEDA/EasyEDA-Project/STM32H747 board';
const projectUuid='761c4fdb8e3e1a273a7eb212bd6961ba8b6efdb0e27d1b0c207735a7e696c24c';
const references={CN3:['8bd1ebd7c6524c9d','45489c1c67834c9bc61a945cd1ee5ff26100193f6348a65fe3f2314efda4915b'],CN4:['ae37a0fb8459ebec','74fbfe9c4eef0cf238db94cb43decf75ff54d052d13e29c14d57de1093ea3913']};
const reference=__taskArgs[0];
if(!references[reference])throw new Error('One exact USB-C footprint reference required');
const [uuid,expectedSha]=references[reference];
const sourceFile=await eda.sys_FileSystem.readFileFromFileSystem(root+'/output/validation/native-'+reference+'-outline5p-absolute-candidate.epru');
if(!sourceFile)throw new Error('Reviewed full canonical footprint candidate missing');
const source=await sourceFile.text();
const digest=Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',new TextEncoder().encode(source))),v=>v.toString(16).padStart(2,'0')).join('');
if(digest!==expectedSha)throw new Error('Full canonical footprint candidate hash mismatch');
const rows=source.split(/\r?\n/).filter(l=>l.includes('||')).map(line=>{const i=line.indexOf('||');return {head:JSON.parse(line.slice(0,i)),body:JSON.parse(line.slice(i+2).replace(/\|$/,''))};});
const counts={};for(const row of rows)counts[row.head.type]=(counts[row.head.type]||0)+1;
if(rows[0]?.body?.uuid!==uuid||rows[0]?.body?.docType!=='FOOTPRINT'||rows.length!==48||counts.PAD!==18||counts.LINE!==5||counts.META!==1)throw new Error('Full canonical USB-C footprint source contract failed');
await eda.dmt_EditorControl.closeDocument(uuid+'@'+projectUuid);
const updated=await eda.lib_Footprint.updateDocumentSource(uuid,projectUuid,source);
if(!updated)throw new Error('USB-C project footprint update failed');
const path=root+'/output/validation/native-'+reference+'-absolute-pad-update-receipt.json';
const saved=await eda.sys_FileSystem.saveFileToFileSystem(path,new Blob([JSON.stringify({reference,uuid,updated,sourceSha256:digest,counts},null,2)]),undefined,false);
return {reference,uuid,updated,saved,path,counts};
