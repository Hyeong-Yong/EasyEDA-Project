const uuid='0ac2a19168000d8e';
const projectUuid='761c4fdb8e3e1a273a7eb212bd6961ba8b6efdb0e27d1b0c207735a7e696c24c';
const root='C:/Dev/EasyEDA/EasyEDA-Project/STM32H747 board';
const stage=__taskArgs[0];
if(stage&&!/^[a-z0-9_-]{3,50}$/.test(stage))throw new Error('Scoped diagnostic Gerber stage required');
const filename=stage?'STM32H747_'+stage+'_DIAGNOSTIC_NOT_FOR_FAB':'STM32H747_DIAGNOSTIC_NOT_FOR_FAB';
const board=await eda.dmt_Board.getBoardInfo('mcu_board');
if(board?.pcb?.uuid!==uuid||board?.schematic?.uuid!=='416c10313f778784')throw new Error('Final board association changed');
await eda.dmt_EditorControl.openDocument(uuid);
if((await eda.dmt_Project.getCurrentProjectInfo())?.uuid!==projectUuid||(await eda.dmt_Pcb.getCurrentPcbInfo())?.uuid!==uuid)throw new Error('Wrong final PCB/project for diagnostic export');
const file=await eda.pcb_ManufactureData.getGerberFile(filename);
if(!file||file.size<10000)throw new Error('Native diagnostic Gerber export is missing or incomplete');
const bytes=await file.arrayBuffer();
const magic=new Uint8Array(bytes.slice(0,4));
if(magic[0]!==80||magic[1]!==75)throw new Error('Native diagnostic exporter did not return a ZIP');
const sha256=Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',bytes)),v=>v.toString(16).padStart(2,'0')).join('');
const path=root+'/output/validation/'+filename+'.zip';
const saved=await eda.sys_FileSystem.saveFileToFileSystem(path,file,undefined,false);
if(!saved)throw new Error('Native diagnostic Gerber ZIP could not be saved');
const receipt={pcbUuid:uuid,projectUuid,path,bytes:file.size,sha256,manufacturingApproved:false,purpose:'Native geometry and drill QA only; no order API was invoked'};
await eda.sys_FileSystem.saveFileToFileSystem(root+'/output/validation/native-diagnostic-gerber-export'+(stage?'-'+stage:'')+'-receipt.json',new Blob([JSON.stringify(receipt,null,2)]),undefined,false);
return receipt;
