const ROOT='C:/Dev/EasyEDA/EasyEDA-Project/STM32H747 board';
const PROJECT_NAME='STM32H747_MCU_BOARD_v19';
const PROJECT_UUID='761c4fdb8e3e1a273a7eb212bd6961ba8b6efdb0e27d1b0c207735a7e696c24c';
const PLAN_PATH=ROOT+'/output/validation/footprint-arc-compatibility-plan.json';
const reference=String(__taskArgs[0]??'').trim();
if(!reference||reference==='all')throw new Error('One reviewed footprint reference is required');
const project=await eda.dmt_Project.getCurrentProjectInfo();
if(!project||(project.name!==PROJECT_NAME&&project.friendlyName!==PROJECT_NAME)||project.uuid!==PROJECT_UUID)throw new Error('Dedicated STM32H747 project required');
const planFile=await eda.sys_FileSystem.readFileFromFileSystem(PLAN_PATH);
if(!planFile)throw new Error('Compatibility plan missing');
const plan=JSON.parse(await planFile.text());
if(plan.schema!=='stm32h747-footprint-arc-compatibility-plan-v2'||plan.summary?.replacement_polys!==84||plan.summary?.deleted_reverse_mates!==0)throw new Error('Reviewed v2 plan contract failed');
const matches=plan.targets.filter(target=>target.reference===reference||target.imported_uuid===reference);
if(matches.length!==1)throw new Error('Exact reviewed footprint target missing');
const target=matches[0];
const sourceFile=await eda.sys_FileSystem.readFileFromFileSystem(ROOT+'/'+target.normalized_preview);
if(!sourceFile)throw new Error('Normalized full footprint source missing');
const source=await sourceFile.text();
const bytes=new TextEncoder().encode(source);
const digest=Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',bytes)),value=>value.toString(16).padStart(2,'0')).join('');
if(digest!==target.normalized_preview_sha256)throw new Error('Normalized source hash mismatch');
const rows=source.split(/\r?\n/).filter(Boolean).map(line=>{
  const raw=line.endsWith('|')?line.slice(0,-1):line;
  const divider=raw.indexOf('||');
  if(divider<0)throw new Error('Malformed normalized source record');
  return {head:JSON.parse(raw.slice(0,divider)),body:JSON.parse(raw.slice(divider+2))};
});
const doc=rows.find(row=>row.head.type==='DOCHEAD')?.body;
if(doc?.uuid!==target.imported_uuid||doc?.docType!=='FOOTPRINT')throw new Error('Full library source identity incorrect');
if(rows.some(row=>row.head.type==='ARC'))throw new Error('Normalized source still contains ARC');
const polyRows=rows.filter(row=>row.head.type==='POLY');
if(polyRows.length!==Number(target.normalized_record_counts.POLY||0))throw new Error('Normalized POLY count mismatch');
const expectedIds=target.transformations.map(transform=>transform.keep_id).sort();
const actualIds=polyRows.map(row=>row.head.id).sort();
if(JSON.stringify(actualIds)!==JSON.stringify(expectedIds))throw new Error('Normalized same-ID POLY set mismatch');
if(target.transformations.some(transform=>(transform.delete_ids||[]).length||transform.kind!=='arc_to_same_id_open_poly_arc'))throw new Error('Plan is not merge-safe one-to-one');
const closed=await eda.dmt_EditorControl.closeDocument(target.imported_uuid+'@'+PROJECT_UUID);
const updated=await eda.lib_Footprint.updateDocumentSource(target.imported_uuid,PROJECT_UUID,source);
if(!updated)throw new Error('Project-library footprint update failed');
const result={schema:'stm32h747-footprint-arc-direct-update-v2',reference:target.reference,uuid:target.imported_uuid,closed,updated,source:target.normalized_preview,sourceSha256:digest,expectedArcCount:0,expectedPolyCount:polyRows.length,expectedPolyIds:actualIds};
const captured=await eda.sys_FileSystem.saveFileToFileSystem(ROOT+'/output/validation/native-footprint-direct-update-'+target.reference+'.json',new Blob([JSON.stringify(result,null,2)+'\n']),undefined,false);
if(!captured)throw new Error('Direct-update result could not be saved');
return {...result,captured};
